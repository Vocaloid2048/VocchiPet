package com.voc2048.vocchiPet.api

/**
 * 寵物的稀有度等級。
 * The rarity level of the pet.
 */
enum class Rarity {
    /** 一般 / Common */
    COMMON,
    /** 不尋常 / Uncommon */
    UNCOMMON,
    /** 稀有 / Rare */
    RARE,
    /** 史詩 / Epic */
    EPIC,
    /** 傳說 / Legendary */
    LEGENDARY,
    /** 神話 / Mythical */
    MYTHICAL
}
